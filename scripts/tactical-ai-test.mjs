import assert from 'node:assert/strict';
import {createNavigationGrid,isWalkablePosition,isSegmentClear2D,findNavigationPath,chooseTacticalGoal,createTacticalBrain,stepTacticalBrain,updateTacticalPath} from '../src/gameplay/tactical-ai.mjs';
const wall={x:0,z:0,halfX:1.5,halfZ:6};
const obstacles=[wall,{x:4,z:4,halfX:1,halfZ:1}];
const grid=createNavigationGrid(obstacles,{min:-10,max:10,cellSize:1,clearance:.4});
assert.equal(isSegmentClear2D({x:-8,z:0},{x:8,z:0},obstacles,.4),false);
const path=findNavigationPath(grid,{x:-8,z:0},{x:8,z:0});
assert.ok(path.length>=2,'A* routes around cover');
let previous={x:-8,z:0};
for(const point of path){assert.ok(isWalkablePosition(grid,point));assert.ok(isSegmentClear2D(previous,point,obstacles,.36));previous=point;}
assert.ok(Math.hypot(previous.x-8,previous.z)<1.1);
assert.deepEqual(findNavigationPath(grid,{x:-8,z:0},{x:8,z:0}),path);
const open=createNavigationGrid([],{min:-20,max:20,cellSize:1,clearance:.4});
const target={x:0,z:0},enemy={x:0,z:16};
const scout=chooseTacticalGoal({type:'scout',position:enemy,target,grid:open,obstacles:[],strafeSign:1});
const heavy=chooseTacticalGoal({type:'heavy',position:enemy,target,grid:open,obstacles:[],strafeSign:1});
const gunner=chooseTacticalGoal({type:'gunner',position:enemy,target,grid:open,obstacles:[],strafeSign:1});
assert.ok(Math.hypot(scout.x,scout.z)<2.8);
assert.ok(Math.hypot(heavy.x,heavy.z)<3.7);
assert.ok(Math.abs(Math.hypot(gunner.x,gunner.z)-12.4)<1.1);
const brain=createTacticalBrain('heavy',target,123);brain.attackCooldown=0;
let step=stepTacticalBrain(brain,{dt:.1,type:'heavy',canAttack:true,hasLineOfSight:true,attackRate:1.3});
assert.equal(step.state,'windup');assert.equal(step.telegraph,true);
step=stepTacticalBrain(brain,{dt:.4,type:'heavy',canAttack:true,hasLineOfSight:true,attackRate:1.3});
assert.equal(step.attack,false);
step=stepTacticalBrain(brain,{dt:.5,type:'heavy',canAttack:true,hasLineOfSight:true,attackRate:1.3});
assert.equal(step.attack,true);assert.equal(step.state,'recover');
const cancel=createTacticalBrain('gunner',target,8);cancel.attackCooldown=0;
stepTacticalBrain(cancel,{dt:.1,type:'gunner',canAttack:true,hasLineOfSight:true,attackRate:1.5});
step=stepTacticalBrain(cancel,{dt:.1,type:'gunner',canAttack:false,hasLineOfSight:false,attackRate:1.5});
assert.equal(step.attack,false);assert.equal(step.state,'search');
const nav=createTacticalBrain('scout',target,44);
const waypoint=updateTacticalPath(nav,{x:-8,z:0},{x:8,z:0},grid,obstacles,.016,'scout');
assert.ok(waypoint&&isWalkablePosition(grid,waypoint));
console.log('ARENA ZERO tactical AI checks passed: A*, cover avoidance, archetype spacing and telegraphed attacks.');
