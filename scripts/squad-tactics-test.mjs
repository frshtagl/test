import assert from 'node:assert/strict';
import {createSquadAssignment,calculateSquadSeparation,relaySquadContact} from '../src/gameplay/squad-tactics.mjs';
const left=createSquadAssignment('scout',1,3,4);
const right=createSquadAssignment('scout',2,3,4);
const gunner=createSquadAssignment('gunner',3,3,4);
const heavy=createSquadAssignment('heavy',4,3,4);
assert.equal(left.squadId,'wave-3-squad-1');
assert.equal(left.role,'flank-left');assert.equal(left.strafeSign,-1);
assert.equal(right.role,'flank-right');assert.equal(right.strafeSign,1);
assert.equal(gunner.role,'support-left');
assert.equal(createSquadAssignment('gunner',4,3,4).role,'support-right');
assert.equal(heavy.role,'anchor');
assert.equal(createSquadAssignment('scout',5,3,4).squadId,'wave-3-squad-2');
assert.throws(()=>createSquadAssignment('medic',1,1),/Unknown/);
assert.throws(()=>createSquadAssignment('scout',0,1),/invalid/);
assert.throws(()=>createSquadAssignment('scout',1,1,4.5),/invalid/);
const self={position:{x:0,z:0},userData:{squadId:left.squadId}};
const ally={position:{x:1,z:0},userData:{squadId:left.squadId}};
const otherSquad={position:{x:0,z:1},userData:{squadId:'different'}};
const separation=calculateSquadSeparation(self.position,[self,ally,otherSquad],left.squadId,self,2.35);
assert.ok(separation.x<0&&Math.abs(separation.z)<1e-9,'Ally separation should push away from a same-squad neighbour');
assert.ok(separation.magnitude>0&&separation.magnitude<=1);
assert.deepEqual(calculateSquadSeparation(self.position,[self,otherSquad],left.squadId,self),{x:0,z:0,magnitude:0});
const malformedAlly={position:{x:NaN,z:0},userData:{squadId:left.squadId}};
assert.deepEqual(calculateSquadSeparation(self.position,[self,malformedAlly],left.squadId,self),{x:0,z:0,magnitude:0});
const coincidentSelf={position:{x:0,z:0},userData:{squadId:'overlap',squadSlot:0}};
const coincidentAlly={position:{x:0,z:0},userData:{squadId:'overlap',squadSlot:1}};
assert.ok(calculateSquadSeparation(coincidentSelf.position,[coincidentSelf,coincidentAlly],'overlap',coincidentSelf).magnitude>0,'Exact spawn overlap must be resolved deterministically');
const source={squadId:'alpha',brain:{lastKnown:{x:0,z:0},lostSightTime:0,repathTimer:1}};
const follower={squadId:'alpha',brain:{lastKnown:{x:8,z:8},lostSightTime:1,repathTimer:2}};
const unrelated={squadId:'beta',brain:{lastKnown:{x:9,z:9},lostSightTime:2,repathTimer:3}};
assert.equal(relaySquadContact(source,[source,follower,unrelated],{x:4,z:-2}),1);
assert.deepEqual(follower.brain.lastKnown,{x:4,z:-2});
assert.equal(follower.brain.lostSightTime,0);assert.equal(follower.brain.repathTimer,0);
assert.deepEqual(unrelated.brain.lastKnown,{x:9,z:9});
assert.equal(relaySquadContact(source,[source,follower],{x:4.2,z:-2}),0,'Small contact drift must not churn a squad route');
console.log('ARENA ZERO squad tactics checks passed: role assignment, squad separation and shared contact memory.');
